"""Coarsen the A-airfoil C-mesh for quick tests (CPU smoke tests, a cheap first GPU run).

Takes every si-th / sj-th / sk-th node in i / j / k (the last node of each direction is always
kept, so the extent and the spanwise period are unchanged) and keeps every block interface
point-matched: blocks 0 and 3 share the wake cut (jmin) with reversed i, so block 3 uses the
mirror of block 0's i indices. Choose sk dividing nk - 1 = 81 (1, 3, 9, 27) to keep the spanwise
spacing uniform. Also writes a case file next to the grid, derived from case.yaml.

    conda run -n pyvista env PYTHONPATH=src python cases/a_airfoil/coarsen.py              # 4 x 2 x 9, ~0.5M cells
    conda run -n pyvista env PYTHONPATH=src python -m wmles_wrap run cases/a_airfoil/case_coarse.yaml
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import yaml

from wmles_wrap.io.plot3d import read_plot3d, write_plot3d

HERE = Path(__file__).resolve().parent


def indices(n: int, stride: int) -> np.ndarray:
    """0, stride, 2*stride, ... plus the last node n - 1."""
    idx = list(range(0, n, stride))
    if idx[-1] != n - 1:
        idx.append(n - 1)
    return np.array(idx)


def coarsen(blocks: list[np.ndarray], si: int, sj: int, sk: int) -> list[np.ndarray]:
    if len(blocks) != 4:
        raise ValueError(f"expected the 4-block A-airfoil C-mesh, got {len(blocks)} blocks")
    nj, nk = blocks[0].shape[1:3]
    if any(b.shape[1:3] != (nj, nk) for b in blocks) or blocks[0].shape[0] != blocks[3].shape[0]:
        raise ValueError(f"unexpected block dimensions {[b.shape[:3] for b in blocks]}")
    jj, kk = indices(nj, sj), indices(nk, sk)
    i0 = indices(blocks[0].shape[0], si)
    ii = [i0, indices(blocks[1].shape[0], si), indices(blocks[2].shape[0], si),
          (blocks[3].shape[0] - 1 - i0)[::-1]]  # wake cut: block 3 mirrors block 0
    return [np.ascontiguousarray(b[i][:, jj][:, :, kk]) for b, i in zip(blocks, ii)]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--grid", default=str(HERE / "a_airfoil_C.xyz"))
    ap.add_argument("--si", type=int, default=4, help="i stride (along the surface / wake)")
    ap.add_argument("--sj", type=int, default=2, help="j stride (wall-normal)")
    ap.add_argument("--sk", type=int, default=9, help="k stride (spanwise)")
    ap.add_argument("--out", default=str(HERE / "a_airfoil_coarse.p3d"))
    ap.add_argument("--case", default=str(HERE / "case_coarse.yaml"), help="case file to write ('' to skip)")
    ap.add_argument("--precision", default="float64", choices=("float32", "float64"))
    ap.add_argument("--partitions", default="auto", help="parallel.partitions (e.g. 6 to test halos on CPU)")
    ap.add_argument("--steps", type=int, default=3000)
    args = ap.parse_args()

    fine = read_plot3d(args.grid)
    coarse = coarsen(fine, args.si, args.sj, args.sk)
    del fine
    out = Path(args.out)
    write_plot3d(out, coarse)
    ncell = sum(int(np.prod([n - 1 for n in b.shape[:3]])) for b in coarse)
    print(f"wrote {out}: {[b.shape[:3] for b in coarse]} nodes, {ncell:,} cells")

    if args.case:
        cfg = yaml.safe_load((HERE / "case.yaml").read_text())
        cfg["grid"] = {"file": out.name if out.parent == Path(args.case).resolve().parent else str(out.resolve()),
                       "format": "plot3d"}
        cfg["numerics"]["precision"] = args.precision
        cfg["parallel"]["partitions"] = int(args.partitions) if args.partitions.isdigit() else args.partitions
        cfg["run"] = {"steps": args.steps, "log_every": 100, "stats_start_time": 0.05, "stats_every": 5,
                      "output_every": args.steps, "restart_every": 1000, "restart_keep": 1}
        cfg["output"]["dir"] = "out_coarse"
        header = (f"# Coarsened A-airfoil test case, generated by coarsen.py (strides i/j/k = {args.si}/{args.sj}/"
                  f"{args.sk}, {ncell:,} cells) from case.yaml; see case.yaml for the documentation.\n")
        Path(args.case).write_text(header + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=None))
        print(f"wrote {args.case}")


if __name__ == "__main__":
    main()
